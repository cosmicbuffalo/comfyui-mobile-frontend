// Writes THIRD_PARTY_NOTICES.md: every npm package bundled into dist/, found
// through the build's source maps, with its license text. Minification strips
// the license comments, so this file is where the bundle carries them.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const assets = path.join(root, 'dist', 'assets');
const packageDirs = new Map();
for (const file of fs.readdirSync(assets)) {
  if (!file.endsWith('.js.map')) continue;
  const { sources = [] } = JSON.parse(fs.readFileSync(path.join(assets, file), 'utf8'));
  for (const source of sources) {
    // Greedy prefix: the innermost node_modules owns the file.
    const match = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(source);
    if (!match) continue;
    const dir = path.resolve(assets, match[1]);
    const { name, version, license } = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    packageDirs.set(`${name}@${version}`, { name, version, license, dir });
  }
}

const sections = [...packageDirs.values()]
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
  .map(({ name, version, license, dir }) => {
    const licenseFile = fs.readdirSync(dir).find(file => /^licen[cs]e/i.test(file));
    if (!licenseFile) throw new Error(`${name}@${version} has no license file to reproduce`);
    const text = fs.readFileSync(path.join(dir, licenseFile), 'utf8').trim();
    return `## ${name} ${version}\n\nLicense: ${license}\n\n\`\`\`text\n${text}\n\`\`\`\n`;
  });

fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), [
  '# Third-party notices',
  '',
  'The built frontend in `dist/` includes the packages below. This file is generated by',
  '`scripts/third-party-notices.mjs` as part of `npm run build`.',
  '',
  ...sections,
].join('\n'));
console.log(`third-party-notices: ${sections.length} package(s)`);
